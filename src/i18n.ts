export function t(key: Key, vars: Record<string, string | number> = {}): string {
  const text = getLanguage() === "ru" ? ru[key] : en[key];
  return text.replace(/\{(\w+)\}/g, (all, name: string) => (name in vars ? String(vars[name]) : all));
}
